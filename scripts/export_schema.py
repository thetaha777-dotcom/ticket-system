"""Write docs/DATABASE_TABLES.md - every table and column - from the SQLAlchemy models.

    python -m scripts.export_schema

The file is generated: do not edit it by hand. Re-run this script after you change a model
(and after you created the Alembic migration for that change). It needs no database.
"""

import os
from pathlib import Path

os.environ.setdefault("DATABASE_URL", "sqlite://")
os.environ.setdefault("SECRET_KEY", "not-used-when-exporting-the-schema")

from sqlalchemy.dialects import postgresql  # noqa: E402

from app import models  # noqa: E402, F401  (importing registers every table)
from app.core.database import Base  # noqa: E402

TARGET = Path(__file__).resolve().parent.parent / "docs" / "DATABASE_TABLES.md"


def column_notes(column) -> str:
    notes = []
    if column.primary_key:
        notes.append("primary key")
    notes += [f"→ `{fk.column.table.name}.{fk.column.name}`" for fk in column.foreign_keys]
    if column.unique:
        notes.append("unique")
    if column.index and not column.unique:
        notes.append("indexed")
    enum_values = getattr(column.type, "enums", None)
    if enum_values:
        notes.append("one of: " + ", ".join(f"`{v}`" for v in enum_values))
    return "; ".join(notes)


def main() -> None:
    dialect = postgresql.dialect()
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    lines = [
        "# Database tables",
        "",
        "> Generated by `python -m scripts.export_schema` from the models in `app/*/models.py` - do not edit by hand.",
        "> For the meaning of the tables and how they relate, read [DATA_MODEL.md](DATA_MODEL.md).",
        "",
        f"{len(tables)} tables. Types are shown as PostgreSQL creates them.",
        "",
    ]
    for table in tables:
        lines += [f"## {table.name}", "", "| Column | Type | Required | Notes |", "|---|---|---|---|"]
        for column in table.columns:
            type_name = column.type.compile(dialect=dialect)
            required = "yes" if not column.nullable else ""
            lines.append(f"| `{column.name}` | {type_name} | {required} | {column_notes(column)} |")
        for constraint in sorted(table.constraints, key=lambda c: str(c.name)):
            if constraint.__class__.__name__ == "UniqueConstraint" and len(constraint.columns) > 1:
                names = ", ".join(f"`{c.name}`" for c in constraint.columns)
                lines.append(f"\nUnique together: {names}.")
        lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote docs/DATABASE_TABLES.md ({len(tables)} tables)")


if __name__ == "__main__":
    main()
