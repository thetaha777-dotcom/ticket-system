import json
import os
from pathlib import Path

os.environ.setdefault("DATABASE_URL", "sqlite://")
os.environ.setdefault("SECRET_KEY", "not-used-when-exporting-the-openapi-document")

from app.main import app 

DOCS = Path(__file__).resolve().parent.parent / "docs"

OPTIONAL_LOGIN = ("/api/v1/events/{ref}",)

def access_label(path: str, operation: dict) -> str:
    if not operation.get("security"):
        return "public"
    if path.startswith(OPTIONAL_LOGIN):
        return "public (login optional)"
    if path.startswith("/api/v1/admin"):
        return "platform admin"
    if path.startswith("/api/v1/organizer"):
        return "organizer of the event"
    if path.startswith("/api/v1/checkin"):
        return "assigned staff"
    return "signed-in user"


def first_sentence(text: str | None) -> str:
    if not text:
        return ""
    line = " ".join(text.strip().split("\n\n")[0].split())
    return line.replace("|", "\\|")


def main() -> None:
    spec = app.openapi()
    DOCS.mkdir(exist_ok=True)
    (DOCS / "openapi.json").write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    groups: dict[str, list[tuple[str, str, str, str]]] = {}
    for path, operations in spec["paths"].items():
        for method, operation in operations.items():
            tag = (operation.get("tags") or ["other"])[0]
            description = first_sentence(operation.get("description")) or operation.get("summary", "")
            groups.setdefault(tag, []).append((method.upper(), path, access_label(path, operation), description))

    total = sum(len(rows) for rows in groups.values())
    lines = [
        "# API reference",
        "",
        "> Generated by `python -m scripts.export_openapi` - do not edit by hand.",
        "> For explanations and worked examples read [API.md](API.md). The same information is available",
        "> interactively at `http://localhost:8000/docs` while the API is running.",
        "",
        f"{total} operations on {len(spec['paths'])} paths. All paths except `/health` start with `/api/v1`.",
        "",
    ]
    for tag, rows in groups.items():
        lines += [f"## {tag}", "", "| Method | Path | Who may call it | What it does |", "|---|---|---|---|"]
        lines += [f"| {method} | `{path}` | {access} | {description} |" for method, path, access, description in rows]
        lines.append("")
    (DOCS / "API_REFERENCE.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote docs/openapi.json and docs/API_REFERENCE.md ({total} operations)")


if __name__ == "__main__":
    main()
